"""Generate marketing/studio/lib/stats.ts from nflverse's games.csv.

Usage (games.csv from https://github.com/nflverse/nfldata/blob/master/data/games.csv):
    python3 marketing/studio/scripts/digit_odds.py path/to/games.csv > marketing/studio/lib/stats.ts

A square's odds are averaged over both orientations (home on the top axis or
the side axis), since a pool doesn't know which team is home.
"""
import collections
import csv
import sys

rows = [
    r for r in csv.DictReader(open(sys.argv[1]))
    if r["home_score"] and r["away_score"] and r["game_type"] and r["season"] < "2026"
]
seasons = sorted({r["season"] for r in rows})
n = len(rows)
pair = collections.Counter()
single = collections.Counter()
finals = collections.Counter()
for r in rows:
    h, a = int(r["home_score"]), int(r["away_score"])
    pair[(h % 10, a % 10)] += 1
    single[h % 10] += 1
    single[a % 10] += 1
    finals[tuple(sorted((h, a), reverse=True))] += 1

# hits[x][y] = games whose final lands on square (x, y), orientation-averaged.
hits = [[(pair[(x, y)] + pair[(y, x)]) / 2 for y in range(10)] for x in range(10)]

out = []
out.append("// Generated by scripts/digit_odds.py from nflverse games.csv. Do not edit by hand.")
out.append(f"// NFL final scores, {seasons[0]}–{seasons[-1]} seasons (regular season + playoffs).")
out.append("")
out.append(f"export const GAMES = {n};")
out.append(f'export const SEASONS = "{seasons[0]}–{seasons[-1]}";')
out.append("")
out.append("/** Share (%) of final team scores ending in each digit 0–9. */")
out.append("export const DIGIT_SHARE = [" + ", ".join(f"{100 * single[d] / (2 * n):.1f}" for d in range(10)) + "];")
out.append("")
out.append("/** HITS[x][y]: games (orientation-averaged) whose final score lands on square x–y. */")
out.append("export const HITS: number[][] = [")
for x in range(10):
    out.append("  [" + ", ".join(f"{v:g}" for v in hits[x]) + "],")
out.append("];")
out.append("")
out.append("/** Most common final scores, as [winner, loser, games]. */")
out.append("export const TOP_FINALS: [number, number, number][] = [")
for (w, l), c in finals.most_common(5):
    out.append(f"  [{w}, {l}, {c}],")
out.append("];")
out.append("")
out.append("/** Chance (%) that a square cashes on the final score. */")
out.append("export const pct = (x: number, y: number): number => (100 * HITS[x][y]) / GAMES;")
print("\n".join(out))
