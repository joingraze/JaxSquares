// Counts which soccer square every goal of the men's world championship would
// have won (2018, 2022 and 2026: every goal has its minute) and writes
// scripts/seo/data/soccerMinutes.ts for the marketing studio's soccer stats:
//
//   for y in 2018 2022 2026; do
//     curl -fsSL https://raw.githubusercontent.com/openfootball/worldcup.json/master/$y/worldcup.json -o wc$y.json
//   done
//   node --experimental-strip-types scripts/seo/soccerStats.ts wc2018.json wc2022.json wc2026.json
//
// openfootball's worldcup.json is public domain. A goal's square follows the
// app's rule (shared/soccer.ts `boardMinute`; soccerStats is checked against it
// in seo.test.ts): first-half stoppage time is the 45th minute, second-half
// stoppage time runs on (90+3' is 93), extra time keeps its last two digits.
// Shoot-out kicks aren't goals. Marketing copy names the tournament without
// its trademarked name, like "the big game".

import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "data/soccerMinutes.ts");

/** The minute's square, 0-99 (shared/soccer.ts `boardMinute`, which Node can't import as is). */
export function boardMinute(minute: number, added = 0): number {
  return ((minute === 45 || minute === 105 ? minute : minute + added) % 100 + 100) % 100;
}

/** "45+2" -> 45 and 2. */
function parseMinute(text: string): { minute: number; added: number } {
  const m = /^\s*(\d{1,3})\s*(?:\+\s*(\d{1,2}))?\s*$/.exec(text);
  if (!m) throw new Error(`soccer stats: unreadable goal minute "${text}"`);
  return { minute: Number(m[1]), added: m[2] ? Number(m[2]) : 0 };
}

interface Goal {
  minute: string | number;
}
interface Match {
  team1: string;
  team2: string;
  /** { ft, et?, p? }, or a bare [a, b] in a few older entries. */
  score?: { ft?: [number, number]; et?: [number, number] } | [number, number];
  goals1?: Goal[];
  goals2?: Goal[];
}

export interface SoccerStats {
  years: number[];
  matches: number;
  goals: number;
  /** Matches with no goal: square 00 wins their goal moments. */
  noGoalMatches: number;
  /** Goals in first-half stoppage time (all on square 45) and second-half stoppage time. */
  firstHalfStoppage: number;
  secondHalfStoppage: number;
  extraTime: number;
  /** squareGoals[m]: goals whose minute lands on square m (00-99). */
  squareGoals: number[];
}

export function countMinutes(files: { year: number; matches: Match[] }[]): SoccerStats {
  const squareGoals = new Array<number>(100).fill(0);
  let matches = 0;
  let goals = 0;
  let noGoalMatches = 0;
  let firstHalfStoppage = 0;
  let secondHalfStoppage = 0;
  let extraTime = 0;
  for (const { year, matches: list } of files) {
    for (const m of list) {
      const sc = m.score;
      const final = Array.isArray(sc) ? sc : (sc?.et ?? sc?.ft);
      if (!final) throw new Error(`soccer stats: ${year} ${m.team1}–${m.team2} has no score`);
      const scored = [...(m.goals1 ?? []), ...(m.goals2 ?? [])];
      // Every goal must have its minute, or the counts would be quietly short.
      if (scored.length !== final[0] + final[1]) {
        throw new Error(`soccer stats: ${year} ${m.team1}–${m.team2} lists ${scored.length} goals for a ${final[0]}–${final[1]} score`);
      }
      matches++;
      if (scored.length === 0) noGoalMatches++;
      for (const g of scored) {
        const { minute, added } = parseMinute(String(g.minute));
        goals++;
        squareGoals[boardMinute(minute, added)]++;
        if (minute === 45 && added > 0) firstHalfStoppage++;
        if (minute === 90 && added > 0) secondHalfStoppage++;
        if (minute > 90) extraTime++;
      }
    }
  }
  return { years: files.map((f) => f.year), matches, goals, noGoalMatches, firstHalfStoppage, secondHalfStoppage, extraTime, squareGoals };
}

export function statsModule(s: SoccerStats): string {
  return [
    "// Generated by scripts/seo/soccerStats.ts from openfootball's worldcup.json (public domain). Do not edit by hand.",
    `// Every goal of the men's world championship, ${s.years.join(", ")}, on the soccer square it would have won.`,
    "",
    `export const YEARS = [${s.years.join(", ")}];`,
    `export const MATCHES = ${s.matches};`,
    `export const GOALS = ${s.goals};`,
    "/** Matches without a goal: square 00 wins. */",
    `export const NO_GOAL_MATCHES = ${s.noGoalMatches};`,
    "/** Goals in first-half stoppage time (every one on square 45). */",
    `export const FIRST_HALF_STOPPAGE = ${s.firstHalfStoppage};`,
    "/** Goals in second-half stoppage time (squares 91 and up). */",
    `export const SECOND_HALF_STOPPAGE = ${s.secondHalfStoppage};`,
    `export const EXTRA_TIME_GOALS = ${s.extraTime};`,
    "",
    "/** SQUARE_GOALS[m]: goals whose minute lands on square m (00-99). */",
    "export const SQUARE_GOALS: number[] = [",
    ...Array.from({ length: 10 }, (_, r) => `  ${s.squareGoals.slice(r * 10, r * 10 + 10).join(", ")},`),
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const paths = process.argv.slice(2);
  if (paths.length === 0) {
    console.error("usage: node --experimental-strip-types scripts/seo/soccerStats.ts wc2018.json wc2022.json wc2026.json");
    process.exit(1);
  }
  const files = paths.map((p) => {
    const year = Number(/(\d{4})/.exec(basename(p))?.[1]);
    if (!year) throw new Error(`soccer stats: name the file by its year (wc2026.json), not ${p}`);
    return { year, matches: (JSON.parse(readFileSync(p, "utf8")) as { matches: Match[] }).matches };
  });
  const stats = countMinutes(files.sort((a, b) => a.year - b.year));
  writeFileSync(OUT, statsModule(stats));
  console.log(`soccer stats: ${stats.goals} goals in ${stats.matches} matches (${stats.years.join(", ")}), written to ${OUT}`);
}
