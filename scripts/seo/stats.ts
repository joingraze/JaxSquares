// Counts how often each squares square hits on an NFL final score, from
// nflverse's games.csv, and writes scripts/seo/data/nflFinals.ts:
//
//   curl -fsSL https://raw.githubusercontent.com/nflverse/nfldata/master/data/games.csv -o games.csv
//   node --experimental-strip-types scripts/seo/stats.ts games.csv          (npm run seo:stats -- games.csv)
//
// The data page (/best-football-squares-numbers) and the marketing studio's
// stat videos both read that file. A season counts once its last game (game
// type "SB") has a score, so a season in progress never skews the table; the
// yearly workflow (.github/workflows/seo-stats.yml) re-runs this after it ends.
//
// A square is averaged over both orientations (home team across the top or
// down the side), since a board doesn't know which team is home.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "data/nflFinals.ts");
const TOP = 10;

/** Minimal CSV: games.csv has no quoted commas in the columns we read, but handle quotes anyway. */
function parseCsv(text: string): Record<string, string>[] {
  const lines = text.split(/\r?\n/).filter((l) => l.length > 0);
  const split = (line: string): string[] => {
    const out: string[] = [];
    let cur = "";
    let quoted = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (quoted) {
        if (ch === '"' && line[i + 1] === '"') {
          cur += '"';
          i++;
        } else if (ch === '"') quoted = false;
        else cur += ch;
      } else if (ch === '"') quoted = true;
      else if (ch === ",") {
        out.push(cur);
        cur = "";
      } else cur += ch;
    }
    out.push(cur);
    return out;
  };
  const [head, ...rows] = lines.map(split);
  return rows.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ""])));
}

export interface FinalsStats {
  games: number;
  firstSeason: string;
  lastSeason: string;
  digitShare: number[];
  hits: number[][];
  topFinals: [number, number, number][];
}

export function countFinals(csv: string): FinalsStats {
  const all = parseCsv(csv).filter((r) => r.home_score !== "" && r.away_score !== "" && r.game_type !== "");
  const complete = new Set(all.filter((r) => r.game_type === "SB").map((r) => r.season));
  const rows = all.filter((r) => complete.has(r.season));
  if (rows.length === 0) throw new Error("stats: no completed seasons in games.csv");
  const seasons = [...complete].sort();
  const pair = new Map<string, number>();
  const single = new Array<number>(10).fill(0);
  // Insertion order breaks ties, like Python's Counter.most_common.
  const finals = new Map<string, number>();
  for (const r of rows) {
    const h = Number(r.home_score);
    const a = Number(r.away_score);
    const key = `${h % 10},${a % 10}`;
    pair.set(key, (pair.get(key) ?? 0) + 1);
    single[h % 10]++;
    single[a % 10]++;
    const final = `${Math.max(h, a)},${Math.min(h, a)}`;
    finals.set(final, (finals.get(final) ?? 0) + 1);
  }
  const n = rows.length;
  const count = (x: number, y: number) => pair.get(`${x},${y}`) ?? 0;
  const hits = Array.from({ length: 10 }, (_, x) => Array.from({ length: 10 }, (_, y) => (count(x, y) + count(y, x)) / 2));
  const digitShare = single.map((c) => Math.round((1000 * c) / (2 * n)) / 10);
  const topFinals = [...finals.entries()]
    .map(([k, c], i) => ({ k, c, i }))
    .sort((p, q) => q.c - p.c || p.i - q.i)
    .slice(0, TOP)
    .map(({ k, c }) => {
      const [w, l] = k.split(",").map(Number);
      return [w, l, c] as [number, number, number];
    });
  return { games: n, firstSeason: seasons[0], lastSeason: seasons[seasons.length - 1], digitShare, hits, topFinals };
}

export function statsModule(s: FinalsStats): string {
  const out = [
    "// Generated by scripts/seo/stats.ts from nflverse games.csv. Do not edit by hand.",
    `// NFL final scores, ${s.firstSeason}–${s.lastSeason} seasons (regular season + playoffs).`,
    "",
    `export const GAMES = ${s.games};`,
    `export const SEASONS = "${s.firstSeason}–${s.lastSeason}";`,
    `export const FIRST_SEASON = ${s.firstSeason};`,
    `export const LAST_SEASON = ${s.lastSeason};`,
    "",
    "/** Share (%) of final team scores ending in each digit 0–9. */",
    `export const DIGIT_SHARE = [${s.digitShare.map((v) => v.toFixed(1)).join(", ")}];`,
    "",
    "/** HITS[x][y]: games (orientation-averaged) whose final score lands on square x–y. */",
    "export const HITS: number[][] = [",
    ...s.hits.map((row) => `  [${row.join(", ")}],`),
    "];",
    "",
    "/** Most common final scores, as [winner, loser, games]. */",
    "export const TOP_FINALS: [number, number, number][] = [",
    ...s.topFinals.map(([w, l, c]) => `  [${w}, ${l}, ${c}],`),
    "];",
    "",
  ];
  return out.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = process.argv[2];
  if (!file) {
    console.error("usage: node --experimental-strip-types scripts/seo/stats.ts path/to/games.csv");
    process.exit(1);
  }
  const stats = countFinals(readFileSync(file, "utf8"));
  writeFileSync(OUT, statsModule(stats));
  console.log(`stats: ${stats.games} games, ${stats.firstSeason}–${stats.lastSeason}, written to ${OUT}`);
}
